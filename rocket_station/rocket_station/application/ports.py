from pathlib import Path
from typing import Protocol

from rocket_station.domain.operation import Operation
from rocket_station.domain.data_source import CsvPreview, DataSource
from rocket_station.domain.calculation import FormulaInfo
from rocket_station.domain.report import Report


class OperationRepository(Protocol):
    def exists(self, code: str) -> bool: ...

    def get(self, code: str) -> Operation: ...

    def add(self, operation: Operation, *, replace: bool = False) -> None: ...

    def update(self, operation: Operation) -> None: ...

    def list_all(self) -> list[Operation]: ...

    def delete(self, code: str) -> None: ...

    def free_code(self, code: str) -> str: ...


class PackageArchive(Protocol):
    def export(self, code: str, destination: Path) -> None: ...

    def read(self, file: Path) -> Operation:
        """Confere o pacote sem instalar nada. Levanta InvalidPackageError."""

    def install(self, file: Path, source_code: str, target_code: str, *, replace: bool) -> None: ...

class CsvReader(Protocol):
    def preview(self, file: Path, max_rows: int = 10) -> CsvPreview: ...

    def rows(self, file: Path, separator: str, encoding: str, limit: int) -> list[list[str]]: ...

    def numeric_columns(
        self, file: Path, separator: str, encoding: str
    ) -> dict[str, list[float | None]]: ...

class SourceRepository(Protocol):
    def list_all(self, code: str) -> list[DataSource]: ...

    def add(self, code: str, source: DataSource, csv_file: Path) -> None: ...

    def save_all(self, code: str, sources: list[DataSource]) -> None: ...

    def csv_path(self, code: str, source: DataSource) -> Path: ...

class FormulaCatalog(Protocol):
    def list(self) -> dict[str, FormulaInfo]: ...

    def load_errors(self) -> dict[str, str]: ...

    def run(
        self,
        formula_id: str,
        inputs: dict[str, list[float | None]],
        parameters: dict[str, float],
        sample_rate_hz: float | None,
    ) -> float: ...

class ReportRepository(Protocol):
    def get(self, code: str) -> Report: ...

    def save(self, code: str, report: Report) -> None: ...