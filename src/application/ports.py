from pathlib import Path
from typing import Protocol

from src.domain.operation import Operation
from src.domain.data_source import CsvPreview, DataSource
from src.domain.calculation import FormulaInfo
from src.domain.report import Report
from src.domain.recording import RawRecord
from src.domain.telemetry import TelemetryConfig


class OperationRepository(Protocol):
    def exists(self, code: str) -> bool: ...

    def get(self, code: str) -> Operation: ...

    def add(self, operation: Operation, *, replace: bool = False) -> None: ...

    def update(self, operation: Operation) -> None: ...

    def list_all(self) -> list[Operation]: ...

    def delete(self, code: str) -> None: ...

    def free_code(self, code: str) -> str: ...

    def touch(self, code: str) -> None: ...


class PackageArchive(Protocol):
    def export(self, code: str, destination: Path) -> None: ...

    def read(self, file: Path) -> Operation:
        """Confere o pacote sem instalar nada. Levanta InvalidPackageError."""

    def install(self, file: Path, source_code: str, target_code: str, *, replace: bool) -> None: ...

class CsvReader(Protocol):
    def preview(self, file: Path, max_rows: int = 10) -> CsvPreview: ...

    def rows(self, file: Path, separator: str, encoding: str, limit: int) -> list[list[str]]: ...

    def numeric_columns(
        self, file: Path, separator: str, encoding: str
    ) -> dict[str, list[float | None]]: ...

class SourceRepository(Protocol):
    def list_all(self, code: str) -> list[DataSource]: ...

    def add(self, code: str, source: DataSource, csv_file: Path) -> None: ...

    def save_all(self, code: str, sources: list[DataSource]) -> None: ...

    def csv_path(self, code: str, source: DataSource) -> Path: ...

    def register(self, code: str, source: DataSource) -> None: ...

class FormulaCatalog(Protocol):
    def list(self) -> dict[str, FormulaInfo]: ...

    def load_errors(self) -> dict[str, str]: ...

    def run(
        self,
        formula_id: str,
        inputs: dict[str, list[float | None]],
        parameters: dict[str, float],
        sample_rate_hz: float | None,
    ) -> float: ...

class ReportRepository(Protocol):
    def get(self, code: str) -> Report: ...

    def save(self, code: str, report: Report) -> None: ...

class StationPort(Protocol):
    is_open: bool

    def list_ports(self) -> list[tuple[str, str]]: ...

    def open(self, port: str, baud: int) -> None: ...

    def close(self) -> None: ...

    def read_lines(self) -> list[str]: ...

    def take_error(self) -> str: ...

    def write_line(self, text: str) -> None: ...


class TelemetryConfigRepository(Protocol):
    def get(self, code: str) -> TelemetryConfig: ...

    def save(self, code: str, config: TelemetryConfig) -> None: ...


class RawWriter(Protocol):
    def write(self, record: RawRecord) -> None: ...

    def close(self) -> None: ...


class RecordingStorage(Protocol):
    def new_id(self, code: str) -> str: ...

    def open_raw(self, code: str, recording_id: str) -> RawWriter: ...

    def read_raw(self, code: str, recording_id: str) -> list[RawRecord]: ...

    def write_table(self, code: str, recording_id: str, names: list[str], rows: list[list]) -> str: ...

    def pending(self, code: str, registered: set[str], ignore: str = '') -> list[str]: ...

class CommandLog(Protocol):
    def append(self, code: str, event: dict) -> None: ...

    def read(self, code: str) -> list[dict]: ...